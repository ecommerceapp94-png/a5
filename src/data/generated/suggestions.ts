export function filterSuggestions(query: string): Suggestion[] {
  const q = query.trim().toLowerCase();
  if (!q) return SUGGESTION_CORPUS.slice(0, 20);
  return SUGGESTION_CORPUS.filter((s) => s.query.includes(q) || s.description.toLowerCase().includes(q)).slice(0, 30);
}